-- Create Role Table
CREATE TABLE Tbl_Role (
    id INT IDENTITY(1,1) PRIMARY KEY,
    role_name VARCHAR(100) NOT NULL, -- Values: SuperAdmin, Admin, User
    
    delete_flag BIT DEFAULT 0,
    create_time DATETIME2,
    create_by INT,
    modify_time DATETIME2,
    modify_by INT
);
GO

-- Create Permission Table
CREATE TABLE Tbl_Permission (
    id INT IDENTITY(1,1) PRIMARY KEY,
    permission_name VARCHAR(100) NOT NULL, -- e.g., CREATE_EVENT, VIEW_RESULTS, VOTE
    
    delete_flag BIT DEFAULT 0,
    create_time DATETIME2,
    create_by INT,
    modify_time DATETIME2,
    modify_by INT
);
GO

-- Create RolePermission Mapping Table
CREATE TABLE Tbl_RolePermission (
    role_id INT,
    permission_id INT,
    
    PRIMARY KEY (role_id, permission_id),
    CONSTRAINT FK_RolePermission_Role FOREIGN KEY (role_id) REFERENCES Tbl_Role(id),
    CONSTRAINT FK_RolePermission_Permission FOREIGN KEY (permission_id) REFERENCES Tbl_Permission(id)
);
GO

-- Create User Table
CREATE TABLE Tbl_User (
    id INT IDENTITY(1,1) PRIMARY KEY,
    role_id INT NOT NULL,
    username VARCHAR(100) UNIQUE NOT NULL, -- Used for login
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL, -- Auto-generated by system
    
    delete_flag BIT DEFAULT 0,
    create_time DATETIME2,
    create_by INT,
    modify_time DATETIME2,
    modify_by INT,
    
    CONSTRAINT FK_User_Role FOREIGN KEY (role_id) REFERENCES Tbl_Role(id)
);
GO

-- Create Event Table
CREATE TABLE Tbl_Event (
    id INT IDENTITY(1,1) PRIMARY KEY,
    event_name VARCHAR(255) NOT NULL,
    description VARCHAR(MAX),
    start_time DATETIME2, -- Users can only vote after this time
    end_time DATETIME2,   -- Users can only vote before this time
    
    delete_flag BIT DEFAULT 0,
    create_time DATETIME2,
    create_by INT,
    modify_time DATETIME2,
    modify_by INT
);
GO

-- Create EventAdmin Mapping Table (Maps which Admins manage which Events)
CREATE TABLE Tbl_EventAdmin (
    event_id INT,
    admin_id INT,
    
    delete_flag BIT DEFAULT 0,
    create_time DATETIME2,
    create_by INT,
    modify_time DATETIME2,
    modify_by INT,
    
    PRIMARY KEY (event_id, admin_id),
    CONSTRAINT FK_EventAdmin_Event FOREIGN KEY (event_id) REFERENCES Tbl_Event(id),
    CONSTRAINT FK_EventAdmin_User FOREIGN KEY (admin_id) REFERENCES Tbl_User(id)
);
GO

-- Create Project Type Table
CREATE TABLE Tbl_ProjectType (
    id INT IDENTITY(1,1) PRIMARY KEY,
    type_name VARCHAR(100) NOT NULL, -- e.g., Hardware, Software
    
    delete_flag BIT DEFAULT 0,
    create_time DATETIME2,
    create_by INT,
    modify_time DATETIME2,
    modify_by INT
);
GO

-- Create Project Table
CREATE TABLE Tbl_Project (
    id INT IDENTITY(1,1) PRIMARY KEY,
    event_id INT NOT NULL,
    project_type_id INT NOT NULL,
    project_name VARCHAR(255) NOT NULL,
    description VARCHAR(MAX),
    
    delete_flag BIT DEFAULT 0,
    create_time DATETIME2,
    create_by INT,
    modify_time DATETIME2,
    modify_by INT,
    
    CONSTRAINT FK_Project_Event FOREIGN KEY (event_id) REFERENCES Tbl_Event(id),
    CONSTRAINT FK_Project_ProjectType FOREIGN KEY (project_type_id) REFERENCES Tbl_ProjectType(id)
);
GO

-- Create EventUser Mapping Table (Authorizes users to participate in events)
CREATE TABLE Tbl_EventUser (
    event_id INT,
    user_id INT,
    
    delete_flag BIT DEFAULT 0,
    create_time DATETIME2,
    create_by INT,
    modify_time DATETIME2,
    modify_by INT,
    
    PRIMARY KEY (event_id, user_id),
    CONSTRAINT FK_EventUser_Event FOREIGN KEY (event_id) REFERENCES Tbl_Event(id),
    CONSTRAINT FK_EventUser_User FOREIGN KEY (user_id) REFERENCES Tbl_User(id)
);
GO

-- Create User Vote Limit Table (Defines vote allocations)
CREATE TABLE Tbl_UserVoteLimit (
    id INT IDENTITY(1,1) PRIMARY KEY,
    user_id INT NOT NULL,
    event_id INT NOT NULL,
    project_type_id INT NOT NULL,
    max_votes INT NOT NULL, -- E.g., 1 vote allowed per project type
    used_votes INT DEFAULT 0,
    
    delete_flag BIT DEFAULT 0,
    create_time DATETIME2,
    create_by INT,
    modify_time DATETIME2,
    modify_by INT,
    
    CONSTRAINT FK_UserVoteLimit_User FOREIGN KEY (user_id) REFERENCES Tbl_User(id),
    CONSTRAINT FK_UserVoteLimit_Event FOREIGN KEY (event_id) REFERENCES Tbl_Event(id),
    CONSTRAINT FK_UserVoteLimit_ProjectType FOREIGN KEY (project_type_id) REFERENCES Tbl_ProjectType(id)
);
GO

-- Create Vote Table (Records actual cast votes)
CREATE TABLE Tbl_Vote (
    id INT IDENTITY(1,1) PRIMARY KEY,
    event_id INT NOT NULL,
    project_id INT NOT NULL,
    user_id INT NOT NULL,
    
    delete_flag BIT DEFAULT 0,
    create_time DATETIME2, -- Serves as the exact timestamp of the vote
    create_by INT,
    modify_time DATETIME2,
    modify_by INT,
    
    CONSTRAINT FK_Vote_Event FOREIGN KEY (event_id) REFERENCES Tbl_Event(id),
    CONSTRAINT FK_Vote_Project FOREIGN KEY (project_id) REFERENCES Tbl_Project(id),
    CONSTRAINT FK_Vote_User FOREIGN KEY (user_id) REFERENCES Tbl_User(id)
);
GO

-- Create Audit Log Table (System-wide tracking)
CREATE TABLE Tbl_AuditLog (
    id INT IDENTITY(1,1) PRIMARY KEY,
    action VARCHAR(50) NOT NULL, -- e.g., CREATE, UPDATE, DELETE, VOTE, LOGIN
    table_name VARCHAR(100) NOT NULL,
    record_id INT NOT NULL,
    user_id INT NOT NULL,
    action_details NVARCHAR(MAX), -- Text/JSON describing the changes
    create_time DATETIME2 DEFAULT GETDATE(),
    CONSTRAINT FK_AuditLog_User FOREIGN KEY (user_id) REFERENCES Tbl_User(id)
);
GO